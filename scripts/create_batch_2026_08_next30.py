def existing_slugs() -> set[str]:
    return {path.stem for path in CONTENT_DIR.rglob("*.md")}


def validate_batch() -> None:
    if len(ARTICLES) != 30:
        raise SystemExit(f"Expected 30 articles, found {len(ARTICLES)}")
    slugs = [str(item["slug"]) for item in ARTICLES]
    if len(slugs) != len(set(slugs)):
        raise SystemExit("Duplicate slug in next-30 batch")
    duplicates = sorted(slug for slug in slugs if slug in existing_slugs())
    if duplicates:
        raise SystemExit(f"Next-30 batch slug already exists: {', '.join(duplicates)}")
    descriptions = [str(item["description"]) for item in ARTICLES]
    if len(descriptions) != len(set(text.casefold() for text in descriptions)):
        raise SystemExit("Duplicate description in next-30 batch")
    metas = [str(item["meta"]) for item in ARTICLES]
    if len(metas) != len(set(text.casefold() for text in metas)):
        raise SystemExit("Duplicate meta description in next-30 batch")
    for item in ARTICLES:
        description = str(item["description"])
        meta = str(item["meta"])
        if len(description) < 70 or len(description) > 220:
            raise SystemExit(f"{item['slug']}: description length is {len(description)}")
        if not description.endswith((".", "!", "?")):
            raise SystemExit(f"{item['slug']}: description must end with punctuation")
        if not 120 <= len(meta) <= 160:
            raise SystemExit(f"{item['slug']}: meta description length is {len(meta)}")
        if int(item["template"]) not in {1, 2, 3}:
            raise SystemExit(f"{item['slug']}: invalid template")


def write_trackers() -> None:
    PLAN_PATH.parent.mkdir(parents=True, exist_ok=True)
    fields = [
        "batch_order",
        "slug",
        "title",
        "category",
        "primary_keyword",
        "primary_icp",
        "search_intent",
        "hero_template",
        "content_status",
        "hero_status",
        "publish_status",
    ]
    with PLAN_PATH.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        for order, item in enumerate(ARTICLES, start=1):
            writer.writerow(
                {
                    "batch_order": order,
                    "slug": item["slug"],
                    "title": item["title"],
                    "category": item["category"],
                    "primary_keyword": item["keyword"],
                    "primary_icp": item["icp"],
                    "search_intent": item["intent"],
                    "hero_template": item["template"],
                    "content_status": "created",
                    "hero_status": "pending",
                    "publish_status": "planned",
                }
            )

    schedule_fields = [
        "batch_order",
        "slug",
        "title",
        "cms_input_at",
        "publish_date_cairo",
        "scheduled_time_cairo",
        "status",
        "blog_post_id",
        "blog_url",
    ]
    with SCHEDULE_PATH.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=schedule_fields)
        writer.writeheader()
        for order, item in enumerate(ARTICLES, start=1):
            publish_date = START_DATE + timedelta(days=(order - 1) // len(SLOTS_CAIRO))
            slot = SLOTS_CAIRO[(order - 1) % len(SLOTS_CAIRO)]
            writer.writerow(
                {
                    "batch_order": order,
                    "slug": item["slug"],
                    "title": item["title"],
                    # The CMS interprets this clock value as application-local time.
                    "cms_input_at": f"{publish_date.isoformat()}T{slot}:00Z",
                    "publish_date_cairo": publish_date.isoformat(),
                    "scheduled_time_cairo": slot,
                    "status": "planned",
                    "blog_post_id": "",
                    "blog_url": "",
                }
            )


def main() -> int:
    parser = argparse.ArgumentParser(description="Create the next 30 FreeIndexer articles after the August patch.")
    parser.add_argument("--overwrite", action="store_true", help="Overwrite batch article files if they already exist.")
    args = parser.parse_args()

    if not args.overwrite:
        validate_batch()
    elif len(ARTICLES) != 30:
        raise SystemExit(f"Expected 30 articles, found {len(ARTICLES)}")

    created = 0
    skipped = 0
    for item in ARTICLES:
        directory = CONTENT_DIR / str(item["category"])
        directory.mkdir(parents=True, exist_ok=True)
        path = directory / f"{item['slug']}.md"
        if path.exists() and not args.overwrite:
            skipped += 1
            continue
        path.write_text(render_article(item), encoding="utf-8")
        created += 1

    write_trackers()
    print(json.dumps({"created": created, "skipped": skipped, "plan": str(PLAN_PATH), "schedule": str(SCHEDULE_PATH)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
